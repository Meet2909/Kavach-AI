import json
import csv
import os

# This script prepares a synthetic Instruct dataset for training the Llama verification node,
# using the provided sensor_maintenance_data.csv from archive (1).

system_prompt = """You are a senior petroleum equipment engineer verifying operational statuses and predictive maintenance triggers generated by other AI models. 
Your job is to:
1. Verify the output against the raw sensor data for accuracy.
2. Provide concrete corrections if the primary model misdiagnosed the fault or maintenance requirement.
3. Output your decision clearly at the end: DECISION: APPROVED, REJECTED, or MODIFIED."""

csv_path = r"..\archive (1)\sensor_maintenance_data.csv"
output_file = "petroleum_verification_dataset.jsonl"

def format_chat_message(system, user, assistant):
    return {
        "messages": [
            {"role": "system", "content": system},
            {"role": "user", "content": user},
            {"role": "assistant", "content": assistant}
        ]
    }

def process_csv():
    if not os.path.exists(csv_path):
        print(f"Error: {csv_path} not found. Are you running this from the verification_node folder?")
        return

    dataset = []
    
    with open(csv_path, 'r', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        for i, row in enumerate(reader):
            # We'll generate synthetic positive and negative examples for the Verification Node
            
            # Extract key features
            sensor_id = row['Sensor_ID']
            eq_id = row['Equipment_ID']
            voltage = row['Voltage (V)']
            temp = row['Temperature (°C)']
            vib = row['Vibration (m/s²)']
            fault_status = row['Fault Status']
            failure_type = row['Failure Type']
            maint_type = row['Maintenance Type']
            
            # The context that the verifier (and the primary model) sees
            sensor_context = f"Sensor {sensor_id} on Equipment {eq_id}: Voltage={voltage}V, Temp={temp}°C, Vibration={vib}m/s²."
            
            # Generate alternating Correct and Incorrect primary model outputs to teach it how to verify
            if i % 2 == 0:
                # Correct Diagnosis Example
                primary_output = f"Diagnosis: {fault_status}. The failure type is {failure_type}. Action: {maint_type} maintenance is required."
                correction = f"VERIFICATION SUCCESSFUL.\n1. Data Alignment: The diagnosis matches the sensor logs. Equipment {eq_id} is correctly flagged with {fault_status} ({failure_type}).\n2. Maintenance: {maint_type} maintenance is appropriate.\nDECISION: APPROVED."
            else:
                # Incorrect Diagnosis Example (forcing the verification node to correct it)
                primary_output = f"Diagnosis: No Fault. Equipment is operating normally. Action: No maintenance required."
                if fault_status == 'No Fault':
                     correction = f"VERIFICATION SUCCESSFUL.\n1. Data Alignment: The diagnosis matches the sensor logs. Equipment {eq_id} shows no anomalies.\nDECISION: APPROVED."
                else:
                     correction = f"VERIFICATION FAILED.\n1. Data Misalignment: The primary model incorrectly claims 'No Fault'. Sensor data indicates {fault_status} with a {failure_type} failure mode.\n2. Correction: Immediate {maint_type} maintenance is required to prevent further damage.\nDECISION: REJECTED."
            
            user_prompt = f"Context: {sensor_context}\n\nPrimary Model Output: '{primary_output}'"
            dataset.append(format_chat_message(system_prompt, user_prompt, correction))

    with open(output_file, 'w', encoding='utf-8') as f:
        for item in dataset:
            f.write(json.dumps(item) + "\n")
            
    print(f"Processed {len(dataset)} examples from CSV and saved to {output_file}.")

if __name__ == "__main__":
    process_csv()
